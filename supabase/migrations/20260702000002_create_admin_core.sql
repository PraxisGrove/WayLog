create schema if not exists admin;

create table if not exists admin.admin_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'readonly' check (role in ('owner', 'admin', 'developer', 'readonly')),
  display_name text,
  enabled boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists admin.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users (id) on delete set null,
  action text not null,
  target_type text,
  target_id text,
  payload jsonb not null default '{}'::jsonb,
  ip inet,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_logs_actor_created_at_idx
  on admin.admin_audit_logs (actor_user_id, created_at desc);

create index if not exists admin_audit_logs_target_idx
  on admin.admin_audit_logs (target_type, target_id);

create index if not exists admin_audit_logs_action_created_at_idx
  on admin.admin_audit_logs (action, created_at desc);

create or replace function admin.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_admin_members_updated_at on admin.admin_members;
create trigger set_admin_members_updated_at
  before update on admin.admin_members
  for each row
  execute function admin.set_updated_at();

alter table admin.admin_members enable row level security;
alter table admin.admin_audit_logs enable row level security;

