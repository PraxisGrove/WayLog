grant all on all functions in schema admin to service_role;

create or replace function public.get_current_admin_member()
returns table (
  user_id uuid,
  role text,
  display_name text,
  enabled boolean,
  note text
)
language sql
security definer
set search_path = admin, public
as $$
  select
    admin_members.user_id,
    admin_members.role,
    admin_members.display_name,
    admin_members.enabled,
    admin_members.note
  from admin.admin_members
  where admin_members.user_id = auth.uid()
    and admin_members.enabled = true
  limit 1;
$$;

create or replace function public.is_current_user_admin()
returns boolean
language sql
security definer
set search_path = admin, public
as $$
  select exists (
    select 1
    from admin.admin_members
    where admin_members.user_id = auth.uid()
      and admin_members.enabled = true
  );
$$;

create or replace function public.record_admin_audit_log(
  p_action text,
  p_target_type text default null,
  p_target_id text default null,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = admin, public
as $$
declare
  v_audit_log_id bigint;
begin
  if not public.is_current_user_admin() then
    raise exception 'Admin permission required' using errcode = '42501';
  end if;

  insert into admin.admin_audit_logs (
    actor_user_id,
    action,
    target_type,
    target_id,
    payload
  )
  values (
    auth.uid(),
    p_action,
    p_target_type,
    p_target_id,
    coalesce(p_payload, '{}'::jsonb)
  )
  returning id into v_audit_log_id;

  return v_audit_log_id;
end;
$$;

revoke all on function public.get_current_admin_member() from public;
revoke all on function public.is_current_user_admin() from public;
revoke all on function public.record_admin_audit_log(text, text, text, jsonb) from public;

grant execute on function public.get_current_admin_member() to authenticated;
grant execute on function public.is_current_user_admin() to authenticated;
grant execute on function public.record_admin_audit_log(text, text, text, jsonb) to authenticated;

