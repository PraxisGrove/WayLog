create or replace function public.record_agent_runtime_event(
  p_user_id uuid,
  p_conversation_id text,
  p_turn_id text,
  p_attempt_id text,
  p_phase text,
  p_prompt_version text,
  p_app_version text,
  p_model_profile text,
  p_model text,
  p_provider text,
  p_status text,
  p_failure_kind text,
  p_duration_ms integer,
  p_input_tokens integer,
  p_output_tokens integer,
  p_total_tokens integer,
  p_tool_events jsonb,
  p_operation_count integer,
  p_escalated_from text,
  p_escalation_reason text
)
returns void
language plpgsql
security definer
set search_path = admin, public
as $$
begin
  if p_phase not in ('route_selector', 'waylog_qa', 'trip_draft', 'itinerary_edit') then
    raise exception 'Unsupported Agent phase';
  end if;
  if p_status not in ('succeeded', 'failed') then
    raise exception 'Unsupported Agent telemetry status';
  end if;
  if jsonb_typeof(coalesce(p_tool_events, '[]'::jsonb)) <> 'array'
    or jsonb_array_length(coalesce(p_tool_events, '[]'::jsonb)) > 16 then
    raise exception 'Invalid Agent tool telemetry';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_tool_events, '[]'::jsonb)) as event
    where jsonb_typeof(event) <> 'object'
      or event - array['name', 'status']::text[] <> '{}'::jsonb
      or not ((event ? 'name') and (event ? 'status'))
      or jsonb_typeof(event -> 'name') <> 'string'
      or jsonb_typeof(event -> 'status') <> 'string'
      or event ->> 'status' not in ('requested', 'completed', 'failed')
      or length(event ->> 'name') not between 1 and 200
  ) then
    raise exception 'Agent tool telemetry contains non-whitelisted fields';
  end if;

  insert into admin.agent_runtime_events (
    user_id,
    conversation_id,
    turn_id,
    attempt_id,
    phase,
    prompt_version,
    app_version,
    model_profile,
    model,
    provider,
    status,
    failure_kind,
    duration_ms,
    input_tokens,
    output_tokens,
    total_tokens,
    tool_events,
    operation_count,
    escalated_from,
    escalation_reason
  )
  values (
    p_user_id,
    left(p_conversation_id, 200),
    left(p_turn_id, 200),
    left(p_attempt_id, 200),
    p_phase,
    left(p_prompt_version, 200),
    left(p_app_version, 200),
    left(p_model_profile, 200),
    left(p_model, 200),
    left(p_provider, 200),
    p_status,
    left(p_failure_kind, 200),
    greatest(0, p_duration_ms),
    greatest(0, p_input_tokens),
    greatest(0, p_output_tokens),
    greatest(0, p_total_tokens),
    coalesce(p_tool_events, '[]'::jsonb),
    least(100, greatest(0, p_operation_count)),
    left(p_escalated_from, 200),
    left(p_escalation_reason, 200)
  );
end;
$$;

