create table if not exists admin.agent_runtime_config (
  singleton boolean primary key default true check (singleton),
  config_version bigint not null default 1 check (config_version > 0),
  enabled boolean not null default true,
  disabled_skill_ids text[] not null default '{}'::text[],
  minimum_app_version text not null default '2026.06.22-0448'
    check (minimum_app_version ~ '^[0-9]+([.-][0-9]+)*$'),
  protocol_version integer not null default 1 check (protocol_version > 0),
  allowed_model_profiles text[] not null default array['router', 'balanced']::text[]
    check (
      cardinality(allowed_model_profiles) > 0
      and allowed_model_profiles <@ array['router', 'balanced', 'quality']::text[]
    ),
  model_profiles jsonb not null default '{
    "router": "deepseek-v4-flash",
    "balanced": "deepseek-v4-flash"
  }'::jsonb
    check (jsonb_typeof(model_profiles) = 'object'),
  minute_limit integer not null default 6 check (minute_limit between 1 and 10000),
  daily_limit integer not null default 60 check (daily_limit between 1 and 10000),
  telemetry_enabled boolean not null default true,
  updated_by uuid references auth.users (id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into admin.agent_runtime_config (singleton)
values (true)
on conflict (singleton) do nothing;

drop trigger if exists set_agent_runtime_config_updated_at
  on admin.agent_runtime_config;
create trigger set_agent_runtime_config_updated_at
  before update on admin.agent_runtime_config
  for each row
  execute function admin.set_updated_at();

create table if not exists admin.agent_runtime_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  conversation_id text,
  turn_id text,
  attempt_id text,
  phase text not null check (
    phase in ('route_selector', 'waylog_qa', 'trip_draft', 'itinerary_edit')
  ),
  prompt_version text,
  app_version text,
  model_profile text,
  model text,
  provider text,
  status text not null check (status in ('succeeded', 'failed')),
  failure_kind text,
  duration_ms integer check (duration_ms is null or duration_ms >= 0),
  input_tokens integer check (input_tokens is null or input_tokens >= 0),
  output_tokens integer check (output_tokens is null or output_tokens >= 0),
  total_tokens integer check (total_tokens is null or total_tokens >= 0),
  tool_events jsonb not null default '[]'::jsonb
    check (jsonb_typeof(tool_events) = 'array'),
  operation_count integer check (operation_count is null or operation_count >= 0),
  escalated_from text,
  escalation_reason text,
  created_at timestamptz not null default now()
);

create index if not exists agent_runtime_events_user_created_idx
  on admin.agent_runtime_events (user_id, created_at desc);
create index if not exists agent_runtime_events_phase_created_idx
  on admin.agent_runtime_events (phase, created_at desc);
create index if not exists agent_runtime_events_failure_created_idx
  on admin.agent_runtime_events (failure_kind, created_at desc)
  where failure_kind is not null;

