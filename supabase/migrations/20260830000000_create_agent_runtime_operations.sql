create or replace function public.get_agent_runtime_usage(
  p_daily_limit integer default 60
)
returns jsonb
language plpgsql
security definer
set search_path = admin, public
as $$
declare
  v_user_id uuid := auth.uid();
  v_window_start timestamptz := now() - interval '24 hours';
  v_daily_used integer := 0;
  v_reset_at timestamptz;
  v_model_calls integer := 0;
  v_tool_calls integer := 0;
  v_duration_ms bigint := 0;
  v_escalations integer := 0;
  v_model_profile text;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_daily_limit <= 0 then
    raise exception 'Daily limit must be positive';
  end if;

  select count(*)::integer, min(called_at) + interval '24 hours'
  into v_daily_used, v_reset_at
  from public.agent_calls
  where user_id = v_user_id
    and called_at > v_window_start;

  select
    count(*) filter (where model is not null)::integer,
    coalesce(sum(jsonb_array_length(tool_events)), 0)::integer,
    coalesce(sum(duration_ms), 0),
    count(*) filter (where escalated_from is not null)::integer
  into v_model_calls, v_tool_calls, v_duration_ms, v_escalations
  from admin.agent_runtime_events
  where user_id = v_user_id
    and created_at > v_window_start;

  select model_profile
  into v_model_profile
  from admin.agent_runtime_events
  where user_id = v_user_id
    and created_at > v_window_start
    and model_profile is not null
  order by created_at desc
  limit 1;

  return jsonb_strip_nulls(jsonb_build_object(
    'dailyLimit', p_daily_limit,
    'dailyUsed', coalesce(v_daily_used, 0),
    'dailyRemaining', greatest(0, p_daily_limit - coalesce(v_daily_used, 0)),
    'resetAt', v_reset_at,
    'modelCalls', coalesce(v_model_calls, 0),
    'toolCalls', coalesce(v_tool_calls, 0),
    'durationMs', coalesce(v_duration_ms, 0),
    'escalations', coalesce(v_escalations, 0),
    'modelProfile', v_model_profile
  ));
end;
$$;

revoke all on function public.get_agent_runtime_usage(integer) from public;
grant execute on function public.get_agent_runtime_usage(integer) to authenticated;

create or replace function public.consume_agent_turn_quota(
  p_minute_limit integer default 6,
  p_daily_limit integer default 60
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_now timestamptz := now();
  v_minute_window_start timestamptz := v_now - interval '60 seconds';
  v_day_window_start timestamptz := v_now - interval '24 hours';
  v_minute_count integer := 0;
  v_day_count integer := 0;
  v_retry_event_at timestamptz;
  v_retry_after integer := 0;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_minute_limit <= 0 or p_daily_limit <= 0 then
    raise exception 'Rate limits must be positive';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v_user_id::text, 0));

  select count(*)::integer into v_minute_count
  from public.agent_calls
  where user_id = v_user_id and called_at > v_minute_window_start;

  if coalesce(v_minute_count, 0) >= p_minute_limit then
    select called_at into v_retry_event_at
    from public.agent_calls
    where user_id = v_user_id and called_at > v_minute_window_start
    order by called_at asc
    offset greatest(v_minute_count - p_minute_limit, 0)
    limit 1;

    v_retry_after := greatest(1, ceil(extract(epoch from (
      coalesce(v_retry_event_at, v_now) + interval '60 seconds' - v_now
    )))::integer);

    return jsonb_build_object(
      'allowed', false,
      'bucket', 'minute',
      'minuteLimit', p_minute_limit,
      'minuteRemaining', 0,
      'retryAfterSeconds', v_retry_after
    );
  end if;

  select count(*)::integer into v_day_count
  from public.agent_calls
  where user_id = v_user_id and called_at > v_day_window_start;

  if coalesce(v_day_count, 0) >= p_daily_limit then
    select called_at into v_retry_event_at
    from public.agent_calls
    where user_id = v_user_id and called_at > v_day_window_start
    order by called_at asc
    offset greatest(v_day_count - p_daily_limit, 0)
    limit 1;

    v_retry_after := greatest(1, ceil(extract(epoch from (
      coalesce(v_retry_event_at, v_now) + interval '24 hours' - v_now
    )))::integer);

    return jsonb_build_object(
      'allowed', false,
      'bucket', 'day',
      'dailyLimit', p_daily_limit,
      'dailyUsed', coalesce(v_day_count, 0),
      'dailyRemaining', 0,
      'retryAfterSeconds', v_retry_after
    );
  end if;

  insert into public.agent_calls (user_id, called_at) values (v_user_id, v_now);

  return jsonb_build_object(
    'allowed', true,
    'minuteLimit', p_minute_limit,
    'minuteRemaining', greatest(0, p_minute_limit - coalesce(v_minute_count, 0) - 1),
    'dailyLimit', p_daily_limit,
    'dailyUsed', coalesce(v_day_count, 0) + 1,
    'dailyRemaining', greatest(0, p_daily_limit - coalesce(v_day_count, 0) - 1)
  );
end;
$$;

revoke all on function public.consume_agent_turn_quota(integer, integer) from public;
grant execute on function public.consume_agent_turn_quota(integer, integer) to authenticated;

