const POLICY_AGREEMENT_KEY = "waylog.legal.agreed_version";

export async function savePolicyAgreement(): Promise<void> {
  await AsyncStorage.setItem(POLICY_AGREEMENT_KEY, LEGAL_POLICY_VERSION);
}

export async function hasAgreedToCurrentPolicy(): Promise<boolean> {
  const agreed = await AsyncStorage.getItem(POLICY_AGREEMENT_KEY);
  return agreed === LEGAL_POLICY_VERSION;
}

